import { Document, HeadingLevel, Packer, Paragraph, TextRun } from "docx";
import ExcelJS from "exceljs";
import pptxgen from "pptxgenjs";

function linesFrom(content) {
  return String(content || "").replace(/\r/g, "").split("\n").slice(0, 1200);
}

function cleanInline(value) {
  return String(value).replace(/\*\*(.*?)\*\*/g, "$1").replace(/\*(.*?)\*/g, "$1").replace(/\x60(.*?)\x60/g, "$1");
}

export async function createOfficeExport(format, { title, content }) {
  const lines = linesFrom(content);

  if (format === "docx") {
    const children = [
      new Paragraph({ text: title, heading: HeadingLevel.TITLE }),
      new Paragraph({ children: [new TextRun({ text: "Generated by ARA - Autonomous Research Assistant", italics: true, color: "777777", size: 18 })] })
    ];
    for (const raw of lines) {
      const line = raw.trim();
      if (!line) { children.push(new Paragraph("")); continue; }
      const heading = line.match(/^(#{1,3})\s+(.+)$/);
      if (heading) {
        children.push(new Paragraph({
          text: cleanInline(heading[2]),
          heading: heading[1].length === 1 ? HeadingLevel.HEADING_1 : heading[1].length === 2 ? HeadingLevel.HEADING_2 : HeadingLevel.HEADING_3
        }));
      } else if (/^[-*]\s+/.test(line)) {
        children.push(new Paragraph({ text: cleanInline(line.replace(/^[-*]\s+/, "")), bullet: { indent: 360 } }));
      } else if (/^\d+[.)]\s+/.test(line)) {
        children.push(new Paragraph({ text: cleanInline(line.replace(/^\d+[.)]\s+/, "")), numbering: { reference: "ara-numbering", level: 0 } }));
      } else {
        children.push(new Paragraph({ children: [new TextRun(cleanInline(line))], spacing: { after: 140, line: 300 } }));
      }
    }
    const doc = new Document({
      creator: "ARA",
      title,
      description: "Research report generated by ARA",
      numbering: { config: [{ reference: "ara-numbering", levels: [{ level: 0, format: "decimal", text: "%1.", alignment: "start", style: { paragraph: { indent: { left: 720, hanging: 260 } } } }] }] },
      sections: [{ properties: {}, children }]
    });
    return {
      buffer: await Packer.toBuffer(doc),
      contentType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      extension: "docx"
    };
  }

  if (format === "xlsx") {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = "ARA";
    workbook.created = new Date();
    const sheet = workbook.addWorksheet("Research Report");
    sheet.columns = [
      { header: "Type", key: "type", width: 18 },
      { header: "Content", key: "content", width: 110 }
    ];
    sheet.addRow({ type: "Title", content: title });
    sheet.addRow({ type: "Generated by", content: "ARA - Autonomous Research Assistant" });
    for (const raw of lines) {
      const line = raw.trim();
      if (!line) continue;
      const heading = line.match(/^(#{1,3})\s+(.+)$/);
      sheet.addRow({ type: heading ? "Heading " + heading[1].length : "Paragraph", content: cleanInline(heading ? heading[2] : line.replace(/^[-*]\s+/, "")) });
    }
    sheet.getRow(1).font = { bold: true, color: { argb: "FF29244B" } };
    sheet.views = [{ state: "frozen", ySplit: 1 }];
    sheet.autoFilter = "A1:B1";
    const meta = workbook.addWorksheet("About");
    meta.addRows([["Property", "Value"], ["Title", title], ["Generated", new Date().toISOString()], ["Generator", "ARA"]]);
    meta.columns = [{ width: 22 }, { width: 90 }];
    return {
      buffer: await workbook.xlsx.writeBuffer(),
      contentType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
      extension: "xlsx"
    };
  }

  if (format === "pptx") {
    const pptx = new pptxgen();
    pptx.layout = "LAYOUT_WIDE";
    pptx.author = "ARA";
    pptx.subject = "Research presentation";
    pptx.title = title;
    pptx.theme = { headFontFace: "Aptos Display", bodyFontFace: "Aptos", lang: "en-US" };

    let slide = pptx.addSlide();
    slide.background = { color: "10131A" };
    slide.addText(title, { x: 0.8, y: 1.5, w: 11.5, h: 1.5, fontFace: "Aptos Display", fontSize: 30, bold: true, color: "FFFFFF", fit: "shrink" });
    slide.addText("ARA - Autonomous Research Assistant", { x: 0.85, y: 3.1, w: 10, h: 0.5, fontSize: 14, color: "B8B1F4" });

    let currentHeading = "Key points";
    let bullets = [];
    const addContentSlide = () => {
      if (!bullets.length) return;
      slide = pptx.addSlide();
      slide.background = { color: "F7F8FC" };
      slide.addText(currentHeading, { x: 0.55, y: 0.35, w: 12.1, h: 0.65, fontFace: "Aptos Display", fontSize: 25, bold: true, color: "29244B", fit: "shrink" });
      const text = bullets.map((item) => ({ text: item, options: { bullet: { indent: 16 }, hanging: 4, breakLine: true } }));
      slide.addText(text, { x: 0.8, y: 1.25, w: 11.6, h: 5.3, fontFace: "Aptos", fontSize: 17, color: "202331", paraSpaceAfterPt: 12, valign: "top", fit: "shrink" });
      bullets = [];
    };

    for (const raw of lines) {
      const line = raw.trim();
      if (!line) continue;
      const heading = line.match(/^#{1,3}\s+(.+)$/);
      if (heading) {
        addContentSlide();
        currentHeading = cleanInline(heading[1]);
      } else {
        const item = cleanInline(line.replace(/^[-*]\s+/, ""));
        if (item.length > 430) {
          for (let i = 0; i < item.length; i += 430) bullets.push(item.slice(i, i + 430));
        } else bullets.push(item);
        if (bullets.length >= 7) addContentSlide();
      }
    }
    addContentSlide();
    const buffer = await pptx.write({ outputType: "nodebuffer" });
    return {
      buffer,
      contentType: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
      extension: "pptx"
    };
  }

  const error = new Error("Unsupported export format.");
  error.status = 400;
  throw error;
}
